"""Authored cross/T junction fixtures matching the normal UI template geometry."""
import math


def junction_source(kind='cross'):
    if kind not in ('cross','tee'):raise ValueError('kind must be cross or tee')
    source={'schema_version':'object-map/1','name':'Authored '+kind+' junction','roads':[],'connections':[],'junctions':[{'id':'junction-1','name':'Authored '+kind}],'signals':[],'objects':[],'rights':{'license':'Internal authored test geometry','source_url':'','redistribution':'permitted','notes':'Generated by AXIOM road editor template; no measured road or sensor evidence'}}
    headings=[0,math.pi/2,math.pi,-math.pi/2] if kind=='cross' else [0,math.pi,-math.pi/2]
    approaches=[]
    for index,h in enumerate(headings):
        road={'id':str(index+1),'name':'Approach '+str(index+1),'origin':{'x':-math.cos(h)*60,'y':-math.sin(h)*60,'z':0,'heading_rad':h},'geometries':[{'kind':'line','length_m':48,'curvature_start':0,'curvature_end':0}],'lanes':[{'id':-1,'width_m':3.5,'speed_limit_mps':6,'lane_change':'none','closed':False},{'id':1,'width_m':3.5,'speed_limit_mps':6,'lane_change':'none','closed':False}],'junction_id':None}
        approaches.append(road);source['roads'].append(road)
    for a in approaches:
        for b in approaches:
            if a==b:continue
            h=a['origin']['heading_rad'];target=b['origin']['heading_rad']+math.pi
            diff=math.atan2(math.sin(target-h),math.cos(target-h));straight=abs(diff)<.01;k=0 if straight else math.copysign(1/12,diff)
            identity=str(len(source['roads'])+1)
            road={'id':identity,'name':f"Connector {a['id']} to {b['id']}",'origin':{'x':-math.cos(h)*12,'y':-math.sin(h)*12,'z':0,'heading_rad':h},'geometries':[{'kind':'line' if straight else 'arc','length_m':24 if straight else 6*math.pi,'curvature_start':k,'curvature_end':k}],'lanes':[{'id':-1,'width_m':3.5,'speed_limit_mps':6,'lane_change':'none','closed':False}],'junction_id':'junction-1'}
            source['roads'].append(road)
            source['connections'] += [{'from_road':a['id'],'from_lane':-1,'to_road':identity,'to_lane':-1},{'from_road':identity,'from_lane':-1,'to_road':b['id'],'to_lane':1}]
    return source


if __name__=='__main__':
    import json,sys
    print(json.dumps(junction_source(sys.argv[1] if len(sys.argv)>1 else 'cross'),indent=2))
