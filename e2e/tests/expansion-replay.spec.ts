import { test, expect } from '@playwright/test';

test('authored temporal replay through normal product authoring, queue, visualization and native download', async ({ page }) => {
  await page.goto('/#replay-specs');
  await expect(page.getByRole('heading', { name: 'Replay specifications' })).toBeVisible();
  const freeze = page.getByRole('button', { name: 'Freeze sequence', exact: true });
  await expect(freeze).toBeEnabled();
  const sourceResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/scene-sequences') && response.request().method() === 'POST');
  await freeze.click();
  const source = await (await sourceResponse).json();
  expect(source.source_kind).toBe('synthetic');
  expect(source.frame_count).toBe(21);
  const replayResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/replay-specs') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save replay specification', exact: true }).click();
  const replay = await (await replayResponse).json();
  expect(replay.request.mode).toBe('planning_closed_loop');
  await page.getByRole('button', { name: 'Check retained inputs', exact: true }).click();
  await expect(page.getByText('Inputs are executable within the declared reference scope.')).toBeVisible();
  await page.getByRole('button', { name: 'Open planning experiment', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Experiments', exact: true })).toBeVisible();
  await expect(page.getByLabel('Saved replay input')).toHaveValue(replay.id);
  await page.getByLabel('Experiment name').fill('Browser authored planning feedback');
  await page.getByRole('button', { name: 'Preview workload', exact: true }).click();
  await expect(page.getByText('1 job', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save frozen experiment', exact: true }).click();
  const submitResponse = page.waitForResponse(response => /\/api\/v1\/experiments\/[^/]+\/executions$/.test(response.url()) && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Submit execution', exact: true }).click();
  const job = await (await submitResponse).json();
  await expect(page.getByText('diagnostic_not_safety_validation', { exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Replay trajectory and object observations' })).toBeVisible();
  await page.getByLabel('Replay timeline').fill('10');
  await expect(page.getByText('Step 11 / 21', { exact: true })).toBeVisible();
  const final = await page.request.get(`/api/v1/experiments/executions/${job.id}`);
  const result = await final.json();
  expect(result.status).toBe('completed');
  expect(result.summary.surrounding_actors).toBe('retained_nonreactive_world_tracks');
  expect(result.summary.observer_counts.jerk.unevaluated).toBe(2);
  const ticks = result.summary.visualization.ticks;
  expect(ticks.some((tick: { ego: { speed_mps: number }; logged_ego: { speed_mps: number } }) => tick.ego.speed_mps !== tick.logged_ego.speed_mps)).toBe(true);
  expect(result.summary.max_trajectory_error_m).toBeGreaterThan(0);
  expect(result.artifacts.map((item: { name: string }) => item.name)).toContain('planning-trace.ndjson');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download sealed receipt', exact: true }).click();
  expect((await download).suggestedFilename()).toBe(`${job.id}.json`);
  await expect(page.getByText('Native evidence downloaded and SHA-256 verified.')).toBeVisible();
  await page.screenshot({ path: test.info().outputPath('planning-feedback.png'), fullPage: true });
});

test('unsupported model substitution blocks preflight before a job is submitted', async ({ page, request }) => {
  const sequences = await (await request.get('/api/v1/scene-sequences')).json();
  const replays = await (await request.get('/api/v1/replay-specs')).json();
  expect(sequences.items.length).toBeGreaterThan(0);
  const replay = replays.items[0];
  await page.goto(`/#experiments?replay=${replay.id}`);
  await expect(page.getByRole('button', { name: 'Preview workload', exact: true })).toBeEnabled();
  await page.getByText('Optional model, sensor and evaluator references', { exact: true }).click();
  await page.getByText('Model JSON', { exact: true }).locator('textarea').fill('{"id":"unsupported-camera-e2e"}');
  await page.getByRole('button', { name: 'Preview workload', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'does not execute camera' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save frozen experiment', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Submit execution', exact: true })).toBeDisabled();
});
