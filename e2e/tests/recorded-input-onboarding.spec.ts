import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');

test('granted original source → exact channel/sample inspection → fresh freeze → reference planning result',async({browser,request},info)=>{
  const sourcePath=info.outputPath('authored-source.mcap');
  execFileSync(process.env.AXIOM_TEST_PYTHON ?? path.join(root,'.venv/bin/python'),[path.join(root,'e2e/fixtures/planning_source_fixture.py'),sourcePath]);
  const imported=await request.post('/api/v1/recordings',{params:{name:'Recorded input browser fixture',source_kind:'synthetic',source:'Authored browser contract, not measured road data'},
    data:readFileSync(sourcePath),headers:{'Content-Type':'application/octet-stream'}});
  expect(imported.status()).toBe(201);const source=await imported.json();
  const project=await(await request.post('/api/v1/projects',{data:{name:'Road input scoped browser fixture'}})).json();
  const tokenResponse=await request.post(`/api/v1/projects/${project.id}/tokens`,{data:{user_label:'Recorded input engineer',role:'Engineer'}});
  const token=(await tokenResponse.json()).token;
  const context=await browser.newContext({baseURL:'http://127.0.0.1:5174'});
  await context.addInitScript(token=>sessionStorage.setItem('axiom.apiToken',token),token);
  const page=await context.newPage();
  await page.goto('/#replay-specs');
  await page.getByLabel('Replay source type').selectOption('recording');
  await expect(page.getByText(/No source grants in this project/)).toBeVisible();
  const granted=await request.post('/api/v1/project-recordings/grants',{data:{project_id:project.id,recording_id:source.id,recording_sha256:source.sha256},
    headers:{'Idempotency-Key':`browser-source-grant-${project.id}`}});
  expect(granted.status()).toBe(201);
  await page.reload();await page.getByLabel('Replay source type').selectOption('recording');
  await expect(page.getByLabel('Granted recording source')).toContainText('Recorded input browser fixture');
  await page.getByLabel('Granted recording source').selectOption(source.id);
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download original MCAP',exact:true}).click();
  const downloaded = await download; const originalCopy = info.outputPath('downloaded-original.mcap');
  expect(downloaded.suggestedFilename()).toBe(`${source.id}.mcap`);
  await downloaded.saveAs(originalCopy);
  expect(createHash('sha256').update(readFileSync(originalCopy)).digest('hex')).toBe(source.sha256);
  await expect(page.getByRole('status')).toContainText('SHA-256 and byte size verified');
  const ego=source.channels.find((channel:{topic:string})=>channel.topic==='/ego-world');
  const objects=source.channels.find((channel:{topic:string})=>channel.topic==='/object-world');
  await page.getByLabel('Recorded ego channel').selectOption(String(ego.id));
  await page.getByLabel('Recorded object channel').selectOption(String(objects.id));
  await page.getByRole('button',{name:'Read exact ego samples',exact:true}).click();
  await page.getByRole('button',{name:'Select loaded samples',exact:true}).click();
  await expect(page.getByText(/Selected 6\/512 exact observations/)).toBeVisible();
  await expect(page.getByRole('button',{name:'Freeze inspected sequence',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Inspect selected inputs',exact:true}).click();
  await expect(page.getByLabel('Recorded source inspection')).toContainText('capture clock and pose');
  await expect(page.getByRole('button',{name:'Freeze inspected sequence',exact:true})).toBeEnabled();
  await page.getByLabel('Ego log offset').fill('1');
  await expect(page.getByRole('button',{name:'Freeze inspected sequence',exact:true})).toBeDisabled();
  await page.getByLabel('Ego log offset').fill('0');
  await page.getByRole('button',{name:'Inspect selected inputs',exact:true}).click();
  const frozenResponse=page.waitForResponse(r=>r.url().endsWith('/scene-sequences/freeze')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Freeze inspected sequence',exact:true}).click();
  const frozen=await(await frozenResponse).json();
  expect(frozen.snapshot.recording_snapshot.sha256).toBe(source.sha256);
  expect(frozen.snapshot.frames.map((frame:{ego_source:{ordinal:number}})=>frame.ego_source.ordinal)).toEqual([1,3,5,7,9,11]);
  await page.getByRole('button',{name:'Save replay specification',exact:true}).click();
  await page.getByRole('button',{name:'Check retained inputs',exact:true}).click();
  await page.getByRole('button',{name:'Open planning experiment',exact:true}).click();
  await page.getByRole('button',{name:'Preview workload',exact:true}).click();
  await page.getByRole('button',{name:'Save frozen experiment',exact:true}).click();
  const submit=page.waitForResponse(r=>/\/experiments\/[^/]+\/executions$/.test(r.url())&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Submit execution',exact:true}).click();const job=await(await submit).json();
  await expect(page.getByRole('img',{name:'Replay trajectory and object observations'})).toBeVisible();
  const terminal=await page.request.get(`/api/v1/experiments/executions/${job.id}`,{headers:{Authorization:`Bearer ${token}`}});
  const result=await terminal.json();expect(result.status).toBe('completed');
  expect(result.fidelity).toBe('recorded_objects_reference_vehicle_feedback');
  expect(result.summary.unevaluated_object_steps).toBe(0);
  await page.screenshot({path:info.outputPath('recorded-reference-result.png'),fullPage:true});
  await context.close();
});
