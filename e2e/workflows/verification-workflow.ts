import { expect, type Page, type TestInfo } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

export async function verificationWorkflow(page:Page,info:TestInfo,source:string,python:string,apiUrl:string,token=''){
 info.setTimeout(180000);
 const headers=token?{Authorization:`Bearer ${token}`}:{ };
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const output=info.outputPath('native-evaluation-inputs');
 execFileSync(python,[path.join(source,'examples/dataset_evaluation_workflow.py'),'--url',apiUrl,'--output',output],{cwd:source,env:{...process.env,ADE2E_API_TOKEN:token,PYTHONPATH:['backend/src','sdk/python/src','integrations/onnx/src','integrations/coco/src'].map(p=>path.join(source,p)).join(path.delimiter)},timeout:100000,maxBuffer:2*1024*1024});
 const summary=JSON.parse(readFileSync(path.join(output,'summary.json'),'utf8'));
 const dataset=await (await page.request.get(`/api/v1/datasets/${summary.dataset_id}?revision=2`,{headers})).json();
 const sources=await Promise.all(summary.inference_job_ids.map(async(id:string)=>(await page.request.get(`/api/v1/perception/jobs/${id}`,{headers})).json()));
 await page.goto('/#validation');
 await page.getByRole('button',{name:'Plans',exact:true}).click();
 await page.getByRole('button',{name:'Create verification plan',exact:true}).click();
 await page.getByLabel('Plan name',{exact:true}).fill('Night pedestrian regression');
 await page.getByLabel('Plan purpose',{exact:true}).fill('Authored pixel contract: gaps and actual native evaluation, not road accuracy');
 await page.getByLabel('Plan author',{exact:true}).fill('Browser declared reviewer');
 await page.getByLabel('Plan dataset',{exact:true}).selectOption(dataset.id);
 await page.getByLabel('Dataset revision',{exact:true}).fill('2');
 await page.getByLabel('Baseline model',{exact:true}).selectOption(sources[0].model_id);
 await page.getByLabel('Candidate model',{exact:true}).selectOption(sources[1].model_id);
 await page.getByLabel('score threshold',{exact:true}).fill('0.6');
 await page.getByLabel('minimum score',{exact:true}).fill('0');
 await page.getByLabel('maximum drop',{exact:true}).fill('0');
 await page.getByLabel('minimum images',{exact:true}).fill('1');
 await page.getByLabel('minimum objects',{exact:true}).fill('0');
 await page.getByLabel('minimum recordings',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Add required condition',exact:true}).click();
 await page.getByLabel('Cell 1 name',{exact:true}).fill('Missing night data');
 await page.getByLabel('Cell 1 lighting',{exact:true}).selectOption('night');
 await page.getByLabel('Cell 1 review note',{exact:true}).fill('Required night data is absent');
 await page.getByLabel('Cell 1 reviewed',{exact:true}).check();
 expect(await page.locator('form input:invalid, form select:invalid').evaluateAll(elements=>elements.map(e=>({label:e.getAttribute('aria-label'),value:(e as HTMLInputElement).value,reason:(e as HTMLInputElement).validationMessage})))).toEqual([]);
 await page.getByRole('button',{name:'Save plan revision',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Night pedestrian regression · revision 1',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Preview A/B workload',exact:true}).click();
 await expect(page.getByTestId('verification-preview')).toContainText('6 images per model');
 await expect(page.getByTestId('verification-preview')).toContainText('data_missing');
 await page.getByLabel('I trust both models and confirm this workload',{exact:true}).check();
 await page.getByRole('button',{name:'Submit plan A/B',exact:true}).click();
 await expect(page.getByTestId('verification-stage')).toContainText('completed',{timeout:60000});
 await expect(page.getByTestId('verification-cell-__overall__')).toHaveText('degraded');
 await expect(page.getByTestId('verification-verdict')).toHaveText('Plan verdict: degraded');
 await expect(page.getByText('data_missing',{exact:true})).toBeVisible();
 const attemptId=await page.getByLabel('Verification attempt',{exact:true}).inputValue();
 const result=await (await page.request.get(`/api/v1/verification-attempts/${attemptId}`,{headers})).json();
 expect(result.report.cells[0].counts.images).toBe(6);
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export sealed result',exact:true}).click();
 const saved=await (await download).path();expect(createHash('sha256').update(readFileSync(saved!)).digest('hex')).toBe(result.manifest_hash);
 await page.getByRole('link',{name:'Investigate A/B images',exact:true}).click();
 await expect(page.getByTestId('evaluation-comparison-status')).toHaveText('comparable');
 await page.getByRole('link',{name:'Return to verification plan',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Night pedestrian regression · revision 1',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Revise plan',exact:true}).click();
 await page.getByLabel('Plan change_reason',{exact:true}).fill('Clarify coverage goal');
 expect(await page.locator('form input:invalid, form select:invalid').evaluateAll(elements=>elements.map(e=>({label:e.getAttribute('aria-label'),value:(e as HTMLInputElement).value,reason:(e as HTMLInputElement).validationMessage})))).toEqual([]);
 await page.getByRole('button',{name:'Save plan revision',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Night pedestrian regression · revision 2',exact:true})).toBeVisible();
 await expect(page.getByTestId('verification-stage')).toContainText('completed');
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.locator('.sidebar').evaluate(element=>element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
 await page.screenshot({path:info.outputPath('verification-mobile.png'),fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:1440,height:1080});await page.screenshot({path:info.outputPath('verification-desktop.png'),fullPage:true,animations:'disabled'});
 expect(errors).toEqual([]);
}
